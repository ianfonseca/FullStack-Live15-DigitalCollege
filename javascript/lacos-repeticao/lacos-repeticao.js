//Laço "for" - Estrutura de repetição com teste lógico no início
for (let i = 1; i <= 10; i++) {
    console.log(i);
}

//Laço "while" - Estrutura de repetição com teste lógico no início
let j = 1;
while (j <= 18) {
    console.log("Você tem " + j + " anos.");
    j++;
}

//Laço "do...while" - Estrutura de repetição com teste lógico no final
let k = 7;
do {
    console.log(k);
    k++;
} while (k <= 10);