//Função com 1 parâmetro
function verNome(nome){
    console.log(`Meu nome é ${nome}`);
}

verNome("Ian")
verNome("Lívia ")
verNome("Liz")

//Função com 2 parâmetros
function soma(n1, n2){
    console.log(`A soma de ${n1} e ${n2} é igual a ${n1 + n2}`)
}

soma(30,40)
soma(70,20)
soma(80,90)